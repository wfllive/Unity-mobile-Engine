// (SHA-1, SHA-256, Adler-32, CRC-32, Base64) — работают и в браузере, и в Node.

/* ------------------------------------------------------------------ */
/*                              SHA-1                                  */
/* ------------------------------------------------------------------ */
export function sha1(bytes) {
  const ml = bytes.length;
  const withPad = ((ml + 8) >> 6) + 1;
  const words = new Uint32Array(withPad * 16);
  for (let i = 0; i < ml; i++) words[i >> 2] |= bytes[i] << (24 - (i % 4) * 8);
  words[ml >> 2] |= 0x80 << (24 - (ml % 4) * 8);
  words[withPad * 16 - 2] = Math.floor((ml * 8) / 0x100000000);
  words[withPad * 16 - 1] = (ml * 8) >>> 0;

  let h0 = 0x67452301, h1 = 0xefcdab89, h2 = 0x98badcfe, h3 = 0x10325476, h4 = 0xc3d2e1f0;
  const w = new Uint32Array(80);
  for (let b = 0; b < withPad; b++) {
    for (let i = 0; i < 16; i++) w[i] = words[b * 16 + i];
    for (let i = 16; i < 80; i++) {
      const n = w[i - 3] ^ w[i - 8] ^ w[i - 14] ^ w[i - 16];
      w[i] = (n << 1) | (n >>> 31);
    }
    let a = h0, bb = h1, c = h2, d = h3, e = h4;
    for (let i = 0; i < 80; i++) {
      let f, k;
      if (i < 20) { f = (bb & c) | (~bb & d); k = 0x5a827999; }
      else if (i < 40) { f = bb ^ c ^ d; k = 0x6ed9eba1; }
      else if (i < 60) { f = (bb & c) | (bb & d) | (c & d); k = 0x8f1bbcdc; }
      else { f = bb ^ c ^ d; k = 0xca62c1d6; }
      const t = (((a << 5) | (a >>> 27)) + f + e + k + w[i]) >>> 0;
      e = d; d = c; c = ((bb << 30) | (bb >>> 2)) >>> 0; bb = a; a = t;
    }
    h0 = (h0 + a) >>> 0; h1 = (h1 + bb) >>> 0; h2 = (h2 + c) >>> 0;
    h3 = (h3 + d) >>> 0; h4 = (h4 + e) >>> 0;
  }
  const out = new Uint8Array(20);
  const dv = new DataView(out.buffer);
  dv.setUint32(0, h0); dv.setUint32(4, h1); dv.setUint32(8, h2);
  dv.setUint32(12, h3); dv.setUint32(16, h4);
  return out;
}

